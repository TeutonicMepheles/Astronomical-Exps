"""Run with Blender --background --python this_file -- source.blend output.js [01|02].

Copy the supplied exterior or section assembly, including UVs and split normals,
into local Three.js attributes. No changes are saved to the source .blend.
"""
import base64
import bpy
import json
from pathlib import Path
import struct
import sys
from mathutils import Vector

arguments = sys.argv[sys.argv.index('--') + 1:]
source, target = map(Path, arguments[:2])
group = arguments[2] if len(arguments) > 2 else '01'
assert group in ('01', '02')
bpy.ops.wm.open_mainfile(filepath=str(source))
source_scene = next(scene for scene in bpy.data.scenes
                    if sum(o.type == 'MESH' and o.name.startswith('Scope_02_') for o in scene.objects) == 8)
bpy.context.window.scene = source_scene
bpy.context.view_layer.update()
objects = sorted((o for o in source_scene.objects
                  if o.type == 'MESH' and o.name.startswith('Scope_' + group + '_')),
                 key=lambda o: o.name)
assert len(objects) == (7 if group == '01' else 8), 'Unexpected supplied telescope part count'
exterior = [o for o in source_scene.objects if o.type == 'MESH' and o.name.startswith('Scope_01_')]
bounds = [o.matrix_world @ Vector(v) for o in exterior for v in o.bound_box]
ground = min(v.z for v in bounds)
scale = 2.6 / (max(v.z for v in bounds) - ground)
offset_z = .774603844 if group == '02' else 0

def packed(values):
    return base64.b64encode(struct.pack('<' + 'f' * len(values), *values)).decode('ascii')

meshes = []
depsgraph = bpy.context.evaluated_depsgraph_get()
for obj in objects:
    evaluated = obj.evaluated_get(depsgraph)
    mesh = evaluated.to_mesh()
    mesh.calc_loop_triangles()
    # The textured project's material explicitly reads DiffuseUV.
    uv = mesh.uv_layers.get('DiffuseUV') or next((layer for layer in mesh.uv_layers if layer.active_render), mesh.uv_layers.active)
    normal_matrix = obj.matrix_world.to_3x3().inverted().transposed()
    positions, normals, uvs = [], [], []
    for triangle in mesh.loop_triangles:
        for li in triangle.loops:
            p = obj.matrix_world @ mesh.vertices[mesh.loops[li].vertex_index].co
            n = (normal_matrix @ mesh.corner_normals[li].vector).normalized()
            positions.extend((p.x * scale, (p.z - offset_z - ground) * scale, -p.y * scale))
            normals.extend((n.x, n.z, -n.y))
            uvs.extend(uv.data[li].uv if uv else (0, 0))
    meshes.append(dict(name=obj.name, position=packed(positions), normal=packed(normals), uv=packed(uvs)))
    evaluated.to_mesh_clear()

target.parent.mkdir(parents=True, exist_ok=True)
property_name = 'observationModel' if group == '01' else 'observationSectionModel'
frame = dict(scale=scale, ground=ground,
             origin=[0, (1.17623231-ground)*scale, .430096605*scale])
target.write_text('/* Supplied ' + source.name + ' / Scope_' + group + '; generated by tools/convert-observation-model.py. */\n'
                  '(function(N){N.' + property_name + '=' + json.dumps(dict(source=source.name, sourceGroup='Scope_' + group, uvMap='DiffuseUV', offsetZ=offset_z, frame=frame, meshes=meshes), separators=(',', ':'))
                  + ';})(window.Newton);\n', encoding='utf-8')
print(f'Exported {len(meshes)} original parts to {target} ({target.stat().st_size} bytes)')
print('FRAME', frame)
