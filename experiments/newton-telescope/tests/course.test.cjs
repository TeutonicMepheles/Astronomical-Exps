/* Behavioral checks: unlocking, invalid placement, revisiting, comparison validity. */
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={window:{}};vm.createContext(context);
for(const file of ['state.js','course-state.js'])vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../js',file),'utf8'),context);
const N=context.window.Newton,c=N.course;
const reflectiveState=()=>JSON.stringify(['mirror','mirrorMounted','mirrorSelection','mirrorFocal','mirrorPosition'].map(k=>c.get()[k]));
const beforeLens=reflectiveState();
assert.equal(c.mountLens('invalid'),false);assert.equal(c.mountLens('concave'),true);assert.equal(c.get().lens,'concave');
c.setConvexShape(85);assert.equal(c.get().convexShape,100,'concave lens does not change the convex control');
c.setConcaveShape(0);assert.equal(c.get().concaveShape,85);
c.setConcaveShape(120);assert.equal(c.get().concaveShape,100);
c.setConcaveShape(91);c.setConcaveShape(NaN);assert.equal(c.get().concaveShape,91);
assert.equal(c.mountLens('convex'),true);assert.equal(c.get().lens,'convex');assert.equal(reflectiveState(),beforeLens);
c.setConcaveShape(85);assert.equal(c.get().concaveShape,91,'convex lens does not change the concave control');
c.setConvexShape(0);assert.equal(c.get().convexShape,92,'shape cannot go below the confirmed minimum');
c.setConvexShape(120);assert.equal(c.get().convexShape,100,'shape cannot exceed the original image');
c.setConvexShape(92);assert.equal(c.get().convexShape,92);c.setConvexShape(NaN);assert.equal(c.get().convexShape,92);
c.removeLens();c.mountLens('convex');assert.equal(c.get().convexShape,92,'removal retains the original-glass shape setting');
c.removeLens();assert.equal(c.get().lens,null);assert.equal(reflectiveState(),beforeLens);
c.mountLens('concave');assert.equal(c.get().concaveShape,91,'removal and swapping retain the concave setting');c.resetStage();assert.equal(c.get().lens,null);
assert.equal(c.get().concaveShape,100,'stage reset restores original concave glass');
assert.equal(c.get().convexShape,100,'stage reset restores the original glass shape');
c.mountLens('convex');c.restart();assert.equal(c.get().lens,null);
assert.equal(c.enter('observation'),false);assert.equal(c.enter('assembly'),false);
assert.equal(c.get().seen.length,0);
c.selectMirror('concave');c.selectMirror('convex');assert.equal(c.get().seen.length,0);assert.equal(c.enter('assembly'),false);
for(const mirror of ['plane','concave','convex']){c.selectMirror(mirror);assert.equal(c.mountMirror(),true);}
assert.equal(c.mountMirror('invalid'),false);assert.equal(c.get().seen.length,3);
c.removeMirror();assert.equal(c.get().mirrorMounted,false);assert.equal(c.get().seen.length,3);
assert.equal(c.enter('assembly'),false,'three reflective mirrors alone do not complete the five-lens lesson');
assert.equal(c.mountLens('concave'),true);assert.equal(c.get().seen.length,4);assert.equal(c.enter('assembly'),false);
assert.equal(c.mountLens('convex'),true);assert.equal(c.get().seen.length,5);assert.equal(c.get().seen.filter((v,i,a)=>a.indexOf(v)===i).length,5);
assert.equal(c.get().seen.join(','),'mirror:plane,mirror:concave,mirror:convex,lens:concave,lens:convex');
c.mountLens('convex');assert.equal(c.get().seen.length,5,'re-installing a lens does not add a completion');
assert.equal(c.enter('assembly'),true);assert.equal(c.mountMirror('plane'),false);
assert.equal(c.mountLens('concave'),false);assert.equal(c.get().lens,'convex','leaving the lens tray preserves the last installed lens');
c.selectPart('primary');assert.equal(c.install('secondary'),false);assert.equal(c.get().installed.length,0);
assert.equal(c.install('primary'),true);assert.equal(c.enter('observation'),false);
c.selectPart('secondary');assert.equal(c.install('secondary'),true);assert.equal(c.enter('observation'),true);
c.enter('mirrors');c.enter('observation');assert.equal(c.get().installed.length,2);
const image='data:image/png;base64,AA==';
const record=(aim={target:N.store.get().target,aligned:true,focused:true})=>c.recordDrawing({optical:N.store.get(),image,aim});
N.store.set({live:false});assert.equal(record(),false);
N.store.set({live:true,target:'saturn',focal:1600,eyepiece:25});assert.equal(record(),false,'clear 64x cannot record the high-power Saturn task');
N.store.set({live:true,eyepiece:38});assert.equal(record(),false,'unobserved target cannot be recorded');
for(const [i,target] of ['saturn','moon','jupiter','pleiades'].entries()){
 N.store.set({target,eyepiece:38-i*3,focal:600+i*100,aperture:100+i*20});
 assert.equal(c.observeTarget(target),false,'alignment cannot complete a target without a record');
 N.store.set({focal:800,eyepiece:25});assert.equal(record(),false,'blur cannot be recorded');
 N.store.set({focal:1600,eyepiece:25});assert.equal(record({target,aligned:false,focused:true}),false,'off-axis capture blocked');
 N.store.set(({saturn:{focal:1600,eyepiece:9},moon:{focal:1500,eyepiece:35},jupiter:{focal:1600,eyepiece:13},pleiades:{focal:1450,eyepiece:50}})[target]);
 assert.equal(record(),true,'clear aligned capture at target-appropriate power counts once');
 assert.equal(record(),false,'same target cannot count twice');
 assert.equal(c.get().records.length,i+1);assert.equal(c.get().complete,i===3);
 const saved=c.get().records[i];assert.equal(saved.field,N.store.metrics(N.store.get()).field);
}
assert.deepEqual(Array.from(c.get().records,r=>[r.focal,r.eyepiece]),[[1600,9],[1500,35],[1600,13],[1450,50]],'later knob changes preserve each recorded setup');
c.resetStage();assert.equal(c.get().records.length,0);assert.equal(c.get().observedTargets.length,0);assert.equal(c.get().complete,false);
c.enter('assembly');c.resetStage();assert.equal(c.canEnter('observation'),false);assert.equal(c.get().records.length,0);
c.restart();assert.equal(c.get().stage,'mirrors');assert.equal(c.get().seen.length,0);assert.equal(c.get().mirrorMounted,false);
console.log('PASS: five-lens recognition gate, course progression and controlled-comparison invariants.');
