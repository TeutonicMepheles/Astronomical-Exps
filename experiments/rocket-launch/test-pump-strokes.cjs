const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:1600,height:900},hasTouch:true});
 await page.goto(process.env.ROCKET_BASE||'http://127.0.0.1:9013/experiments/rocket-launch/');
 const pump=page.locator('.pump-control'),upper=page.locator('.pump-upper');
 const count=async()=>Number((await page.locator('#pump-count').textContent()).match(/\d+/)[0]);
 const transform=()=>upper.evaluate(e=>getComputedStyle(e).transform);
 const box=await pump.boundingBox(),x=box.x+box.width/2,y=box.y+box.height/2;
 assert.equal(await count(),0);
 await page.mouse.click(x,y);assert.equal(await count(),1);
 await page.mouse.click(x,y);assert.equal(await count(),2);
 await page.mouse.move(x,y);await page.mouse.down();await page.waitForTimeout(170);
 const first=await transform();await page.waitForTimeout(180);
 assert.notEqual(await transform(),first);
 assert.deepEqual(await pump.boundingBox(),box,'pump hit area stays fixed');
 await page.waitForTimeout(1200);await page.mouse.up();
 assert.ok(await count()>=5);
 assert.equal(await transform(),'matrix(1, 0, 0, 1, 0, 0)');
 const stopped=await count();await page.waitForTimeout(300);assert.equal(await count(),stopped);
 await page.getByRole('button',{name:'重新开始',exact:true}).click();assert.equal(await count(),0);
 await pump.focus();await page.keyboard.down('Space');await page.waitForTimeout(100);
 await page.keyboard.down('Space');await page.waitForTimeout(100);await page.keyboard.up('Space');
 assert.equal(await count(),1,'key repeat must not start extra holds');
 await page.touchscreen.tap(x,y);assert.equal(await count(),2);
 await page.mouse.move(x,y);await page.mouse.down();await page.waitForTimeout(100);
 await pump.dispatchEvent('pointercancel');const cancelled=await count();
 await page.waitForTimeout(300);assert.equal(await count(),cancelled);
 assert.equal(await transform(),'matrix(1, 0, 0, 1, 0, 0)');await page.mouse.up();
 await page.emulateMedia({reducedMotion:'reduce'});await pump.focus();
 await page.keyboard.down('Enter');await page.waitForTimeout(800);
 assert.equal(await transform(),'matrix(1, 0, 0, 1, 0, 0)');
 await page.keyboard.up('Enter');assert.ok(await count()>cancelled);
 await page.getByRole('button',{name:'重新开始',exact:true}).click();assert.equal(await count(),0);
 for(let i=1;i<=6;i++){await page.touchscreen.tap(x,y);assert.equal(await count(),i);}await page.keyboard.down('Enter');await page.waitForTimeout(800);assert.equal(await count(),6,'maximum is six pumps');await page.keyboard.up('Enter');await browser.close();console.log('PASS pump counts, fixed target, animation, release/reset, keyboard repeat, touch, cancellation, reduced motion');
})();
