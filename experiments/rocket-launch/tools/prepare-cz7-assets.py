"""Crop LibTV Seedream 5.5 2K masters without anisotropic resizing.
All shell slices retain source pixels and share one scale owned by cz7.js.
"""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parents[1]
src=root/'docs/review/cz7-generation'; dest=root/'assets/cz7';dest.mkdir(exist_ok=True)
core=Image.open(src/'长征七号等比芯箭2K.png').convert('RGBA').crop((664,166,874,2593))
cuts=[0,round(core.height*.245),round(core.height*.455),round(core.height*.49),core.height]
for j,name in enumerate(['fairing','upper-stage','interstage','lower-stage']):
 core.crop((0,cuts[j],core.width,cuts[j+1])).save(dest/(name+'.png'),optimize=True)
f=Image.open(dest/'fairing.png');mid=f.width//2
f.crop((0,0,mid,f.height)).save(dest/'fairing-left.png');f.crop((mid,0,f.width,f.height)).save(dest/'fairing-right.png')
booster=Image.open(src/'长征七号等比助推器2K.png').convert('RGBA').crop((641,167,896,2573));booster.save(dest/'booster.png',optimize=True)
payload=Image.open(src/'长征七号载荷2K.png').convert('RGBA').crop((569,288,1112,2221));payload.save(dest/'payload.png',optimize=True)
inside=Image.open(src/'长征七号同源透视2K.png').convert('RGBA')
inside.crop((702,1430,824,1805)).save(dest/'oxygen-tank.png',optimize=True)
inside.crop((702,1880,824,2300)).save(dest/'fuel-tank.png',optimize=True)
core.crop((14,core.height-110,98,core.height)).save(dest/'nozzle.png',optimize=True)
geometry={'core':{'width':core.width,'height':core.height,'cuts':cuts},'booster':{'width':booster.width,'height':booster.height},'payload':{'width':payload.width,'height':payload.height}}
(dest/'asset-geometry.js').write_text('// Generated by tools/prepare-cz7-assets.py; native source-pixel dimensions.\nexport const SOURCE_GEOMETRY='+json.dumps(geometry)+';\n',encoding='utf-8')
manifest={'model':'基本型长征七号，两级四助推','generator':'LibTV CLI / Seedream 5.5 / 2K / transparent','canvas':'https://www.liblib.tv/canvas?projectId=1e4009fc34bf46ecb3ecdf4869b352fd','logicalHeight':700,'referenceDiametersMetres':{'core':3.35,'booster':2.25,'fairing':4.2},'note':'原生像素连续裁片、无宽高拉伸；同一母版统一缩放。外形和内部布置为教学插画，不以像素宽度冒充工程尺寸。','sourceGeometry':geometry,'sprites':{p.name:list(Image.open(p).size) for p in dest.glob('*.png')}}
(dest/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
