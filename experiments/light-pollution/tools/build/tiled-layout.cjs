/* Tiled image-collection objects -> existing scene transforms. No new renderer. */
const fs=require('node:fs'),path=require('node:path');
function compile(map,layout,tileset){
 if(map.orientation!=='orthogonal'||map.infinite||map.width*map.tilewidth!==layout.width||map.height*map.tileheight!==layout.height)throw Error('Tiled canvas must match the finite scene');
 if(map.tilesets.length!==1||tileset.objectalignment!=='topleft')throw Error('Use one image collection with explicit top-left alignment');
 const first=map.tilesets[0].firstgid,seen=new Set(),items=[];
 for(const layer of map.layers){
  if(layer.type!=='objectgroup'||layer.draworder!=='index'||layer.offsetx||layer.offsety||layer.parallaxx&&layer.parallaxx!==1||layer.parallaxy&&layer.parallaxy!==1)throw Error('Use indexed object layers without offsets or parallax');
  for(const o of layer.objects){
   const id=o.name,source=layout.layers.find(l=>l.id===id),tile=tileset.tiles.find(t=>t.id===o.gid-first);
   if(!source||seen.has(id)||!tile||path.basename(tile.image)!==source.file)throw Error('Unknown, duplicate or mismatched image object: '+id);
   if(o.rotation||!Number.isInteger(o.gid)||o.gid<first||o.gid>=0x10000000)throw Error('Rotation and flipping are unsupported: '+id);
   const h=source.height||source.width*tile.imageheight/tile.imagewidth,s=o.width/source.width;
   if(![o.x,o.y,o.width,o.height,s].every(Number.isFinite)||s<.1||s>4||Math.abs(o.height/h-s)>1e-5)throw Error('Use finite positions and uniform scale 0.1–4: '+id);
   if(['front-water','back-water'].includes(id)&&s!==1)throw Error('Water must retain its original size');
   const opacity=layer.opacity??1;if(!Number.isFinite(opacity)||opacity<0||opacity>1)throw Error('Invalid layer opacity');
   // Tiled serializes doubles with slightly different precision; stabilize sub-nanopixel noise.
   const n=value=>Math.round(value*1e9)/1e9;
   seen.add(id);items.push({id,x:n(o.x),y:n(o.y),scale:n(s),sourceX:n(source.x),sourceY:n(source.y),opacity,visible:layer.visible!==false&&o.visible!==false,locked:layer.locked===true});
  }
 }
 if(items.length!==layout.layers.length)throw Error('Every existing scene layer must occur exactly once');
 return {version:1,id:'tiled-sample-20261112',width:layout.width,height:layout.height,items};
}
module.exports={compile};
if(require.main===module){
 const root=path.resolve(__dirname,'../..'),mapFile=path.resolve(process.argv[2]||path.join(root,'scenes/tiled-sample/city.tmj'));
 const map=JSON.parse(fs.readFileSync(mapFile)),tileset=map.tilesets[0].source?JSON.parse(fs.readFileSync(path.resolve(path.dirname(mapFile),map.tilesets[0].source))):map.tilesets[0];
 const layout=JSON.parse(fs.readFileSync(path.join(root,'assets/panorama-20261111/layout.json'))),profile=compile(map,layout,tileset);
 const out=path.join(root,'scenes/tiled-sample/layout.js');
 fs.writeFileSync(out,'/* Generated by tools/build/tiled-layout.cjs. */\nwindow.LP_TILED_LAYOUT='+JSON.stringify(profile,null,2)+';\n');
 console.log('Converted Tiled image objects:',profile.items.length);
}
