const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:900},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8381/experiments/earth-circumference/textured.html');
 await page.waitForTimeout(350);
 const state=()=>page.evaluate(()=>({date:window.__globe.observationDate,spin:window.__globe.spin,position:document.querySelector('.orbit-current').style.transform}));
 const initial=await state();
 await page.locator('[data-orbit-play]').click();
 await page.waitForTimeout(950);
 assert.notEqual((await state()).date,initial.date,'Explicit play advances even with reduced-motion preference');
 await page.locator('[data-orbit-pause]').click();
 const paused=await state();
 await page.waitForTimeout(250);
 assert.deepEqual(await state(),paused,'Pause holds date, spin and exact fractional position');
 await page.locator('.orbit-spin-button').click();
 const range=page.locator('#orbit-spin-range');
 const box=await range.boundingBox();
 await page.mouse.click(box.x+box.width*.5,box.y+box.height/2);
 await page.waitForTimeout(80);
 const middle=await state();
 assert.equal(middle.date,paused.date);assert.equal(middle.position,paused.position);
 assert.ok(Math.abs(middle.spin-paused.spin)>150,'Click changes rotation at fixed orbit position');
 await page.mouse.move(box.x+box.width*.5,box.y+box.height/2);
 await page.mouse.down();await page.mouse.move(box.x+box.width*.8,box.y+box.height/2,{steps:12});await page.mouse.up();
 assert.ok((await state()).spin>middle.spin+70,'Dragging changes rotation');
 await range.press('Escape');
 assert.equal(await page.locator('.orbit-spin-popover').isVisible(),false);
 await page.locator('[data-orbit-reset]').click();
 await page.waitForTimeout(80);
 const reset=await state();
 assert.equal(reset.date,initial.date);assert.equal(reset.spin,initial.spin);
 assert.equal(await page.locator('[data-orbit-pause]').getAttribute('aria-pressed'),'true');
 await page.locator('.orbit-spin-button').click();
 await page.locator('#orbit-spin-range').fill('40');
 await page.waitForTimeout(40);
 const held=await state();
 await page.locator('[data-orbit-play]').click();
 await page.waitForTimeout(700);
 await page.locator('[data-orbit-pause]').click();
 const played=await state();
 const drift=await page.evaluate(()=>{const wrap=value=>((value+540)%360)-180;return Math.abs(wrap(window.__globe.spin-(window.__globe.noonSpin()+40)));});
 assert.notEqual(played.date,held.date,'Playback still advances the date');
 assert.ok(drift<0.6,`Spin stays at the new date alignment plus the slider offset, drift ${drift}`);
 await page.locator('[data-orbit-reset]').click();
 for(const date of ['2026-03-22','2026-06-21','2026-09-21','2026-12-21']){
  await page.evaluate(date=>window.__globe.observationDate=date,date);await page.waitForTimeout(40);
  await page.locator('.orbit-spin-button').click();
  const popup=await page.locator('.orbit-spin-popover').boundingBox();
  assert.ok(popup.x>=0&&popup.y>=80&&popup.x+popup.width<=1600&&popup.y+popup.height<752,'Popover stays inside scene');
  await page.locator('#orbit-spin-range').press('Escape');
 }
 await page.setViewportSize({width:1280,height:720});await page.waitForTimeout(50);
 await page.locator('.orbit-spin-button').click();
 assert.equal(await page.locator('.orbit-spin-popover').isVisible(),true);
 assert.deepEqual(errors,[]);
 console.log('PASS play/pause/reset, fixed-orbit spin click/drag, keyboard close, four-season popup bounds, 1280 viewport');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
