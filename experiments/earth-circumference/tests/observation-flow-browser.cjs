  const target=window.__globe.camera().subsolar;
  const values=document.querySelector('.observation-pin path').getAttribute('d').match(/-?\d+(?:\.\d+)?/g).map(Number);
  return Math.hypot(values[2]-target.x,values[3]-target.y);
