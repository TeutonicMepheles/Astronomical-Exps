const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('../../../node_modules/playwright');
(async () => {
 const browser = await chromium.launch();
 try {
  const page = await browser.newPage({ viewport: { width:1600, height:900 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('requestfailed', request => errors.push(request.url()));
  await page.goto(pathToFileURL(path.resolve(__dirname,'../index.html')).href);
  await page.waitForFunction(() => window.meteorExperiment);
  assert.equal(await page.evaluate(() => meteorExperiment.state().error), '');
  assert.deepEqual(await page.evaluate(() => meteorExperiment.state().combos.map(c => c.size)), ['small','large']);
  await page.locator('#launch').click();
  assert.equal(await page.evaluate(() => meteorExperiment.state().phase), 'running');
  await page.waitForFunction(() => meteorExperiment.state().phase === 'result', null, { timeout:10000 });
  assert.equal(await page.evaluate(() => meteorExperiment.state().count), 1);
  const first = await page.evaluate(() => meteorExperiment.state().records[0]);
  assert.deepEqual(first.combos.map(c => c.speed), ['medium','medium']);
  assert.deepEqual(first.combos.map(c => c.angle), ['90','90']);
  assert.notEqual(first.sides[0].whole, first.sides[1].whole);
  first.sides.forEach(side => { assert.notEqual(side.whole, side.cutaway); assert(side.section.find(p => p.x === 0).height < -1); });
  assert(first.sides[0].visual.radius < first.sides[1].visual.radius);
  assert(first.sides[0].visual.depth < first.sides[1].visual.depth);
  assert(first.sides[0].visual.spread < first.sides[1].visual.spread);
  await page.locator('#cutView').click();
  assert.equal(await page.locator('#result0').getAttribute('src'), first.sides[0].cutaway);
  assert.equal(await page.locator('#annotations0').isVisible(), true);
  assert.match(await page.locator('#annotations0').getAttribute('aria-label'), /坑宽.*坑深/);
  assert.equal(first.sides[0].annotations.cutaway.baseline.y, first.sides[1].annotations.cutaway.baseline.y, 'Shared ground baseline');
  assert.deepEqual(first.sides[0].annotations.cutaway.framing, first.sides[1].annotations.cutaway.framing);
  assert(first.sides[0].annotations.cutaway.framing.frustum[1] < 23.5, 'Cutaway framing must enlarge the section');
  assert(first.sides[0].annotations.cutaway.floor.y < first.sides[1].annotations.cutaway.floor.y, 'Projected depth must preserve the visible difference');
  const stats = await page.evaluate(() => meteorExperiment.stats());
  assert(stats.every(item => !item.active));
  assert.deepEqual(stats[0].cutCamera, stats[1].cutCamera, 'Both cutaway views must share the exact camera and scale');
  for (const {cutCamera} of stats) {
    assert(cutCamera.direction.every((value,index) => value === [0,0,-1][index]), 'Cutaway camera must be perpendicular to z=0, without pitch or yaw');
    const [left,right,top,bottom] = cutCamera.frustum;
    assert(Math.abs((right-left)/(top-bottom)-cutCamera.aspect)<1e-10, 'Horizontal and vertical world units must use the same pixel scale');
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('#annotations0 .rc-trace').first().evaluate(node => getComputedStyle(node).animationName), 'none');
  await page.locator('#reset').click();
  await page.locator('[data-side="1"][data-value="medium"]').click();
  await page.locator('#launch').click();
  await page.waitForFunction(() => meteorExperiment.state().count === 2);
  await page.locator('#overview').click();
  assert.equal(await page.locator('#overviewCards img').count(), 6);
  await page.locator('#closeOverview').click();
  await page.locator('[data-side="0"][data-value="medium"]').click();
  assert.equal(await page.locator('#launch').isDisabled(), true, 'Identical factor choices are not a controlled contrast');
  await page.locator('[data-factor="speed"]').click();
  await page.locator('#launch').click();
  await page.waitForFunction(() => meteorExperiment.state().count === 3);
  const speed = await page.evaluate(() => meteorExperiment.state().records[2]);
  assert.equal(speed.combos[0].size, speed.combos[1].size);
  assert.equal(speed.combos[0].angle, speed.combos[1].angle);
  assert(speed.sides[0].visual.radius < speed.sides[1].visual.radius);
  await page.locator('[data-factor="angle"]').click();
  await page.locator('#launch').click(); await page.waitForFunction(() => meteorExperiment.state().count === 4);
  const angle = await page.evaluate(() => meteorExperiment.state().records[3]);
  assert.deepEqual(angle.combos.map(c => c.size), ['medium','medium']);
  assert.deepEqual(angle.combos.map(c => c.speed), ['medium','medium']);
  assert.notEqual(angle.sides[0].outcome.shape, angle.sides[1].outcome.shape);
  await page.locator('[data-mode="world"]').click();
  await page.locator('[data-key="speed"][data-side="shared"][data-value="high"]').click();
  const worlds = await page.evaluate(() => meteorExperiment.state().combos);
  assert.deepEqual({...worlds[0],scene:'moon'}, worlds[1]);
  await page.locator('#launch').click(); await page.waitForFunction(() => meteorExperiment.state().count === 5);
  const worldResult = await page.evaluate(() => meteorExperiment.state().records[4]);
  assert(worldResult.sides[0].visual.radius < worldResult.sides[1].visual.radius);
  const warmed = await page.evaluate(() => meteorExperiment.stats());
  await page.locator('#launch').click(); await page.waitForFunction(() => meteorExperiment.state().count === 6);
  const repeated = await page.evaluate(() => meteorExperiment.state().records[5]);
  assert.equal(repeated.sides[0].whole,worldResult.sides[0].whole,'Identical inputs must produce identical geometry and captures');
  assert.equal(repeated.sides[1].cutaway,worldResult.sides[1].cutaway);
  const after = await page.evaluate(() => meteorExperiment.stats());
  // Earth uploads its soil texture on first use. Compare repeated runs after that
  // legitimate cache warm-up, while geometry must match the initial scene count.
  after.forEach((item,i) => { assert(!item.active); assert.equal(item.geometries,stats[i].geometries); assert.equal(item.textures,warmed[i].textures); });
  await page.locator('#openRecords').click();
  assert.equal(await page.locator('#recordBody tbody tr').count(),2);
  assert.equal(await page.locator('#recordBody img').count(),8);
  await page.locator('#deleteLast').click();
  assert.equal(await page.evaluate(() => meteorExperiment.state().count),5);
  await page.locator('#closeRecords').click();
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.locator('#launch').click(); await page.locator('#cancel').click();
  await page.waitForTimeout(4200);
  assert.equal(await page.evaluate(() => meteorExperiment.state().count),5);
  assert.equal(await page.evaluate(() => meteorExperiment.state().phase),'setup');
  await page.setViewportSize({width:1200,height:900});
  await page.waitForFunction(() => Math.abs(document.querySelector('#lab').getBoundingClientRect().height-675)<1);
  const box = await page.locator('#lab').boundingBox(); assert(Math.abs(box.height-675)<1); assert(Math.abs(box.y-112.5)<1);
  assert(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight));
  assert.deepEqual(errors,[]);
  console.log('PASS paired launches, controlled inputs, three-grade overview, Earth/Moon lock, real cutaway capture, paired records, deterministic replay, cancellation, bounded GPU resources and 16:9.');
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
