const {chromium}=require('../../../node_modules/playwright');
const assert=require('node:assert/strict'),path=require('node:path'),os=require('node:os');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch();
 try{
  const page=await browser.newPage({viewport:{width:1600,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'..','index.html')).href);
  await page.waitForSelector('#angle');
  assert(await page.locator('#sunOverlay [data-measure-label=length]').isHidden(),'Hide shadow length before measurement');
  const scale=page.locator('#lunarShadowScale [data-model-scale]');
  await scale.waitFor();
  const scalePath=await scale.getAttribute('d');
  assert.equal(await page.locator('#lunarShadowScale text').textContent(),'20 km');
  assert(await page.locator('#sunOverlay [data-measure-label=height]').isHidden(),'Hide height before calculation');
  const settle=()=>page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  const count=()=>page.locator('[data-point]').count();
  const phase=p=>page.waitForFunction(v=>document.querySelector('.view.side').dataset.measurePhase===v,p);
  const confirm=async()=>{await page.locator('#start').click();await settle();};
  const choose=async()=>{
    await page.locator(`[data-rim-candidate][data-side=right]`).first().click();await settle();
    assert.equal(await count(),2,'One A click creates both endpoints');
    const points=await page.locator('[data-point]').evaluateAll(es=>es.map(e=>({x:+e.dataset.modelX,y:+e.dataset.modelY,z:+e.dataset.modelZ})));
    assert(points[0].x>points[1].x,'A stays on the right of its own down-sun B');
    assert.equal(points[0].z,points[1].z);
    assert(points[0].x>=0,'A lies on the right side of the crater');
    const length=parseFloat((await page.locator('#sunOverlay [data-measure-label=length]').textContent()).split('=')[1]);
    assert(Math.abs(length-(points[0].x-points[1].x))<.011);
    const angle=+await page.locator('#angle').inputValue();
    assert(Math.abs(points[0].y-points[1].y-length*Math.tan(angle*Math.PI/180))<.02);
    assert.equal(await page.locator('#sunOverlay [data-measure-label=length]').count(),1);
    assert(await page.locator('#sunOverlay [data-measure-label=length]').isVisible());
    assert(await page.locator('#sunOverlay [data-measure-label=height]').isHidden(),'Selecting another peak hides the old height result');
      const legs=await page.evaluate(()=>{
      const root=document.getElementById('sunOverlay'),dots=[...root.querySelectorAll('[data-section-point] > circle:first-child')].map(e=>({x:+e.getAttribute('cx'),y:+e.getAttribute('cy')}));
      const leg=axis=>{const p=root.querySelector(`[data-measure-axis=${axis}]`),a=p.getPointAtLength(0),b=p.getPointAtLength(p.getTotalLength());return {start:{x:a.x,y:a.y},end:{x:b.x,y:b.y},visible:p.style.visibility}};
      return {a:dots[0],b:dots[1],baseline:leg('baseline'),vertical:leg('vertical')};
    });
    const near=(a,b)=>assert(Math.abs(a-b)<.01);
    near(legs.baseline.start.x,legs.b.x);near(legs.baseline.start.y,legs.b.y);
    near(legs.baseline.end.x,legs.a.x);near(legs.baseline.end.y,legs.b.y);
    near(legs.vertical.start.x,legs.a.x);near(legs.vertical.start.y,legs.b.y);
    near(legs.vertical.end.x,legs.a.x);near(legs.vertical.end.y,legs.a.y);
    assert.equal(legs.baseline.visible,'visible','The baseline is visible as soon as A is selected');
    assert.equal(await scale.getAttribute('d'),scalePath,'The reference scale does not change with the selected shadow');
    assert.equal(legs.vertical.visible,'hidden');

    assert.equal(await page.locator('#top').getAttribute('data-measure-zoom'),'0.66');
    assert(Number(await page.locator('#section').getAttribute('data-measure-zoom'))>1);
    for(const el of await page.locator('[data-measure-axis=horizontal]').all())assert.equal(await el.getAttribute('stroke-dashoffset'),'0');
    return length;
  };
  assert.equal(await page.locator('#intensity,#cut,#measure').count(),0,'No light-strength, free section or manual shadow-length control');
  assert.equal(await page.locator('#angle').getAttribute('min'),'35');
  assert.equal(await page.locator('#angle').getAttribute('max'),'70');
  await page.locator('#angle').focus();await page.keyboard.press('Home');await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#angle').inputValue(),'35');
  await page.keyboard.press('End');await page.keyboard.press('ArrowRight');assert.equal(await page.locator('#angle').inputValue(),'70');
  await page.locator('#angle').fill('35');await page.locator('#confirmLight').click();await settle();
  assert.equal(await page.locator('[data-rim-candidate]').count(),0,'Confirm outline before selecting');
  await page.locator('#top').click({position:{x:400,y:450}});assert.equal(await count(),0);
  await page.locator('#rimRadius').press('ArrowRight');await settle();
  assert.equal(await page.locator('#rimRadius').inputValue(),'115');
  await page.locator('#rimRadius').fill('70');await confirm();
  assert.equal(await page.locator('[data-rim-candidate]').count(),0,'Bad outline offers no interior points');
  assert(await page.locator('#start').isVisible(),'An invalid outline stays on the outline step');
  assert.match(await page.getByText(/这个辅助圆附近没有明显投影/).textContent(),/没有明显投影/);
  await page.locator('#rimRadius').fill('110');await settle();assert(await page.locator('#start').isVisible());
  await confirm();
  assert(await page.locator('#sunOverlay [data-measure-label=length]').isHidden(),'Confirming the rim does not reveal results');
  assert(await page.locator('#sunOverlay [data-measure-label=height]').isHidden());
  assert.equal(await page.locator('[data-rim-candidate][data-side=left]').count(),0);
  assert((await page.locator('[data-rim-candidate][data-side=right]').count())>0);
  await page.locator('#top').click({position:{x:400,y:450}});assert.equal(await count(),0,'Only candidate controls can select A');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-rim-candidates.png')});
  const right=await choose();
  const before=await page.locator('#sunOverlay [data-measure-label=length]').textContent();
  await page.locator('#section').click({position:{x:300,y:600}});assert.equal(await page.locator('#sunOverlay [data-measure-label=length]').textContent(),before);
  await page.evaluate(()=>{
    window.angleFrames=[];window.angleObserver=new MutationObserver(()=>{
      const baseline=document.querySelector('#sunOverlay [data-measure-axis=baseline]'),arc=document.querySelector('#sunOverlay [data-angle-arc]');
      const vertical=document.querySelector('#sunOverlay [data-measure-axis=vertical]');
      if(baseline&&arc&&vertical)window.angleFrames.push([+baseline.getAttribute('stroke-dashoffset'),+arc.getAttribute('stroke-dashoffset'),+vertical.getAttribute('stroke-dashoffset'),+document.querySelector('[data-measure-label=height]').getAttribute('opacity')]);
    });window.angleObserver.observe(document.getElementById('sunOverlay'),{subtree:true,attributes:true,childList:true});
  });
  await page.locator('#height').click();await phase('done');await settle();
  assert(await page.locator('[data-solar-angle]').count());
  assert(await page.evaluate(()=>{
    window.angleObserver.disconnect();
    const frames=window.angleFrames;
    return frames.every(([b,a])=>b===0&&a===0)
      && frames.some(([, ,v,opacity])=>v>0&&v<1&&opacity>0&&opacity<1);
  }),'Height animates directly while the angle and baseline are already visible');
  assert(+await page.locator('#sunOverlay [data-angle-label] text').getAttribute('font-size')>=22);
  assert(await page.locator('#sunOverlay [data-measure-label=height]').isVisible());
  assert(Math.abs(parseFloat((await page.locator('#sunOverlay [data-measure-label=height]').textContent()).split('=')[1])-right*Math.tan(35*Math.PI/180))<.02);
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-rim-right-measured.png')});
  await page.locator('[data-rim-candidate][data-side=right]').nth(1).click();await settle();
  assert(await page.locator('#sunOverlay [data-measure-label=height]').isHidden(),'Reselecting a peak clears the previous height');
  // Cancel height animation via lighting change; no delayed old result may reappear.
  await page.locator('#height').click();
  for(let i=0;i<3;i++)await page.locator('#previousStep').click();await page.locator('#angle').fill('70');await settle();await page.waitForTimeout(1100);
  assert.equal(await page.locator('[data-measure-label]').count(),0,'Lighting changes hide stale results');
  assert.equal(await page.locator('[data-rim-candidate]').count(),0);assert(await page.locator('#confirmLight').isHidden(),'An unsuitable angle cannot start measurement');
  await page.locator('#angle').fill('35');
  await page.locator('#confirmLight').click();await confirm();await settle();
  assert.equal(await page.locator('[data-rim-candidate][data-side=left]').count(),0);await choose();
  await page.emulateMedia({reducedMotion:'reduce'});await page.locator('#height').click();await phase('done');
  const idle=await page.locator('#lunarBoundaryPicker').evaluate(el=>new Promise(resolve=>{let n=0;const o=new MutationObserver(()=>n++);o.observe(el,{subtree:true,attributes:true,childList:true});setTimeout(()=>{o.disconnect();resolve(n)},400)}));
  assert.equal(idle,0,'No ongoing circle/candidate updates when idle');
  await page.locator('#previousStep').click();await page.locator('#previousStep').click();await settle();assert.equal(await count(),0);assert.equal(await page.locator('[data-rim-candidate]').count(),0);assert(await page.locator('#start').isVisible());
  assert.equal(await page.locator('[data-measure-label]').count(),0,'Reframing hides all results');
  await page.setViewportSize({width:1200,height:900});await settle();
  await page.locator('#rimPanel [data-nudge="5"]').click();
  assert.equal(await page.locator('#rimRadius').inputValue(),'115','Stepper works after letterboxing');
  await page.locator('#rimRadius').fill('110');await confirm();await choose();
  const stage=await page.locator('main').boundingBox();assert(Math.abs(stage.height-675)<1&&Math.abs(stage.y-112.5)<1);
  await page.locator('#height').click();await phase('done');
  await page.getByRole('button',{name:'重新实验'}).click();await settle();
  assert.equal(await page.locator('#angle').inputValue(),'35');
  assert(await page.locator('#angle').isEnabled());
  assert.equal(await count(),0);
  assert.equal(await page.locator('[data-measure-label]').count(),0);
  assert(await page.locator('#height').isHidden());
  assert.deepEqual(errors,[]);
  console.log('PASS adjustable outline, right-rim candidate-only A, automatic B/length, height animation, invalidation, no-shadow recovery, reduced motion, idle and scaled touch geometry.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
