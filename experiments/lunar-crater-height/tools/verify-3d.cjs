const { chromium } = require('../../../node_modules/playwright');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const os = require('node:os');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.join(__dirname, '..', '月球环形山影长测量实验(2).html')).href);
  await page.screenshot({ path: path.join(os.tmpdir(), 'lunar-crater-3d-initial.png') });
  if(await page.locator('#sunHandle').count())throw new Error('Sun diagram visible before measurement');
  await page.locator('#angle').fill('45');
  if(await page.locator('#angleValue').textContent()!=='45°')throw new Error('Pre-measurement angle control failed');
  await page.locator('#angle').fill('35');
  const sideBox=await page.locator('#section').boundingBox();
  await page.mouse.move(sideBox.x+450,sideBox.y+480);
  await page.mouse.down();
  await page.mouse.move(sideBox.x+550,sideBox.y+480,{steps:10});
  await page.mouse.up();
  if(Number(await page.locator('#cutValue').textContent())>-30)throw new Error('Rightward dragging must move the section right in the initial camera');
  await page.locator('#cut').fill('0');
  await page.mouse.move(sideBox.x+450,sideBox.y+480);
  await page.mouse.down();
  await page.mouse.move(sideBox.x+350,sideBox.y+480,{steps:10});
  await page.mouse.up();
  if(Number(await page.locator('#cutValue').textContent())<30)throw new Error('Leftward dragging must move the section left in the initial camera');
  for(const limit of ['-155','155']){
    await page.locator('#cut').fill(limit);
    if(await page.locator('#cutValue').textContent()!==limit)throw new Error('Cut range does not cover terrain');
  }
  await page.locator('#cut').fill('0');
  const topBox=await page.locator('#top').boundingBox();
  await page.mouse.move(topBox.x+topBox.width/2,topBox.y+topBox.height/2);
  await page.mouse.down();
  await page.mouse.move(topBox.x+topBox.width/2,topBox.y+topBox.height/2+50,{steps:6});
  await page.mouse.up();
  if(Number(await page.locator('#cutValue').textContent())<15)throw new Error('Top cut-line dragging before measurement failed');
  await page.locator('#start').click();
  await page.locator('#cut').fill('20');
  const cutLineY=topBox.height*0.5625;
  await page.locator('#top').click({position:{x:130,y:cutLineY}});
  if(!(await page.locator('#status').textContent()).includes('阴影'))throw new Error('Shadowed point was not rejected');
  await page.locator('#top').click({ position: { x: 205, y: cutLineY } });
  const firstPoint = await page.locator('#status').textContent();
  if (!firstPoint.includes('已同步放置图钉')) throw new Error('Top-view selection failed: '+firstPoint);
  await page.locator('#measure').click();
  const firstLength=parseFloat(await page.locator('#lengthValue').textContent());
  if(!(firstLength>0))throw new Error('A single pin must be sufficient to measure');
  await page.locator('#section').click({ position: { x: 665, y: 470 } });
  const secondPoint = await page.locator('#status').textContent();
  if (!secondPoint.includes('已同步放置图钉')) throw new Error('Section-view selection failed: '+secondPoint);
  if(await page.locator('#lengthValue').textContent()!=='—')throw new Error('Replacing the pin retained old length');
  await page.locator('#measure').click();
  if ((await page.locator('#lengthValue').textContent()) === '—') throw new Error('Shadow measurement failed');
  await page.locator('#height').click();
  if ((await page.locator('#heightValue').textContent()) === '—') throw new Error('Height calculation failed');
  const measured=parseFloat(await page.locator('#lengthValue').textContent()),calculated=parseFloat(await page.locator('#heightValue').textContent());
  if(Math.abs(calculated-measured*Math.tan(35*Math.PI/180))>0.011)throw new Error('Height formula mismatch');
  await page.screenshot({ path: path.join(os.tmpdir(), 'lunar-crater-3d-preview.png') });
  const sunBox=await page.locator('#sunHandle').boundingBox();
  const overlayBox=await page.locator('#sunOverlay').boundingBox();
  const cutBeforeSun=await page.locator('#cutValue').textContent();
  await page.mouse.move(sunBox.x+sunBox.width/2,sunBox.y+sunBox.height/2);
  await page.mouse.down();
  const scale=overlayBox.height/330;
  await page.mouse.move(overlayBox.x+overlayBox.width/2+60*scale,overlayBox.y+overlayBox.height/2-(90*Math.sqrt(3)/2+7)*scale,{steps:8});
  await page.mouse.up();
  if(await page.locator('#angle').inputValue()!=='60')throw new Error('Sun dragging did not set the elevation angle');
  if(await page.locator('#cutValue').textContent()!==cutBeforeSun)throw new Error('Sun dragging moved the section');
  if((await page.locator('#lengthValue').textContent())!=='—')throw new Error('Angle change retained stale measurement');
  for(const angle of ['10','85']){
    await page.locator('#angle').fill(angle);
    await page.screenshot({path:path.join(os.tmpdir(),`lunar-shadow-${angle}.png`)});
  }
  await page.locator('#angle').fill('35');
  await page.locator('#section').click({position:{x:400,y:470}});
  if(!(await page.locator('#status').textContent()).includes('已同步放置图钉'))throw new Error('Below-datum point was rejected');
  await page.locator('#measure').click();
  if(await page.locator('#lengthLabel').textContent()!=='基准面距离 L')throw new Error('Below-datum distance was mislabeled as a shadow');
  await page.locator('#height').click();
  const belowElevation=parseFloat(await page.locator('#heightValue').textContent());
  if(!(belowElevation<0))throw new Error('Below-datum elevation was not negative');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-below-datum.png')});
  const button=await page.locator('#measure').boundingBox();
  if(button.height<44||button.width<44)throw new Error('Control hit area is below 44 px at the logical stage size');
  const font=await page.locator('body').evaluate(el=>getComputedStyle(el).fontFamily);
  if(!font.includes('system-ui'))throw new Error('Shared UI font is not applied');
  await page.setViewportSize({width:1200,height:900});
  const stage=await page.locator('main').boundingBox();
  if(Math.abs(stage.width-1200)>1||Math.abs(stage.height-675)>1||Math.abs(stage.y-112.5)>1)throw new Error('16:9 stage did not scale and center');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-layout-4by3.png')});
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('3D page loaded; cut:', await page.locator('#cutValue').textContent(), 'top selection:', firstPoint, 'side selection:', secondPoint);
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
