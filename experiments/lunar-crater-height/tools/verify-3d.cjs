const {chromium}=require('../../../node_modules/playwright');
const assert=require('node:assert/strict');
const path=require('node:path'),os=require('node:os');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch();
 try{
  const page=await browser.newPage({viewport:{width:1600,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'..','index.html')).href);
  await page.waitForSelector('#section');
  const settle=()=>page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  await settle();
  const selected=()=>page.locator('[data-point]').count();
  const phase=()=>page.locator('.view.side').getAttribute('data-measure-phase');
  const pick=async x=>{await page.locator('#top').click({position:{x,y:450}});await settle();};
  const waitPhase=p=>page.waitForFunction(v=>document.querySelector('.view.side').dataset.measurePhase===v,p);
  const measureManually=async()=>{
    await page.locator('#measure').click();await waitPhase('horizontal-done');
    await page.locator('#height').click();await settle();
    assert.ok(await page.locator('#sunOverlay [data-solar-angle]').count());
    assert.equal(await page.locator('#heightValue').textContent(),'—');
    await page.locator('#height').click();await waitPhase('done');
  };
  assert.ok((await page.locator('#top').boundingBox()).x<(await page.locator('#section').boundingBox()).x);
  const cutGuide=page.locator('[data-cut-guide]');
  assert.equal(await cutGuide.getAttribute('stroke-dasharray'),'9 7');
  assert.match(await page.locator('#cutHint').textContent(),/拖动虚线/);
  const initialGuideY=Number(await cutGuide.getAttribute('y1'));
  await page.locator('#cut').evaluate(el=>{el.value='20';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.waitForFunction(y=>Number(document.querySelector('[data-cut-guide]').getAttribute('y1'))!==y,initialGuideY);
  await page.locator('#cut').evaluate(el=>{el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await settle();
  assert.equal(await selected(),0);assert.equal(await page.locator('[data-boundary]').count(),0);
  await page.locator('#start').click();
  await pick(700);assert.equal(await selected(),0,'Lit surface rejected');
  await pick(580);assert.equal(await selected(),0,'Shadow interior rejected');
  await pick(472);assert.equal(await selected(),1,'Start boundary accepted');
  await pick(166);assert.equal(await selected(),1,'Endpoint from another shadow interval rejected');
  await pick(472);assert.equal(await selected(),1,'Duplicate boundary rejected');
  await pick(580);assert.equal(await selected(),1,'Interior cannot be second endpoint');
  await page.locator('#top').click({position:{x:675,y:350}});assert.equal(await selected(),1,'Off-section selection rejected');
  await pick(675);assert.equal(await selected(),2,'Matching end boundary accepted');
  await page.waitForTimeout(2200);
  assert.equal(await phase(),'idle','Picking two points must not auto-measure');
  assert.equal(await page.locator('#lengthValue').textContent(),'—');
  assert.ok(await page.locator('#lunarCloseup').isHidden(),'Large triangle should stay in the main view');
  await page.evaluate(()=>{
    window.testInk=[];
    window.testInkObserver=new MutationObserver(()=>{
      const path=document.querySelector('#sunOverlay [data-measure-axis=horizontal]');
      if(path)window.testInk.push(Number(path.getAttribute('stroke-dashoffset')));
    });
    window.testInkObserver.observe(document.querySelector('#sunOverlay'),{subtree:true,attributes:true,childList:true});
  });
  await page.locator('#measure').click();
  await waitPhase('horizontal');
  assert.equal(await page.locator('#heightValue').textContent(),'—');
  assert.equal(await page.locator('#sunOverlay [data-measure-axis=vertical]').getAttribute('stroke-dashoffset'),'1');
  await waitPhase('horizontal-done');await page.waitForTimeout(1100);
  assert.ok(await page.evaluate(()=>{window.testInkObserver.disconnect();return window.testInk.some(v=>v>0&&v<1);}), 'Horizontal line must have intermediate animation frames');
  assert.equal(await phase(),'horizontal-done','Horizontal drawing must not auto-start height');
  assert.equal(await page.locator('#heightValue').textContent(),'—');
  assert.equal(await page.locator('[data-solar-angle]').count(),0);
  await page.locator('#height').click();await settle();
  assert.ok(await page.locator('#sunOverlay [data-solar-angle]').count());
  assert.equal(await phase(),'horizontal-done');
  assert.equal(await page.locator('#heightValue').textContent(),'—');
  await page.locator('#height').click();await waitPhase('vertical');
  assert.notEqual(await page.locator('#lengthValue').textContent(),'—');
  assert.equal(await page.locator('#heightValue').textContent(),'—','Height result cannot precede vertical animation');
  await page.waitForTimeout(250);
  assert.equal(await page.locator('#sunOverlay [data-measure-axis=horizontal]').getAttribute('stroke-dashoffset'),'0');
  assert.ok(Number(await page.locator('#sunOverlay [data-measure-axis=vertical]').getAttribute('stroke-dashoffset'))<1);
  await waitPhase('done');await settle();
  const points=await page.locator('[data-point]').evaluateAll(es=>es.map(e=>Number(e.dataset.modelX)));
  const length=parseFloat(await page.locator('#lengthValue').textContent()),height=parseFloat(await page.locator('#heightValue').textContent());
  assert.ok(Math.abs(length-Math.abs(points[1]-points[0]))<.011);
  assert.ok(Math.abs(height-length*Math.tan(35*Math.PI/180))<.02);
  assert.equal(await page.locator('#sunOverlay [data-measure-axis=vertical]').getAttribute('stroke-dashoffset'),'0');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-crater-3d-preview.png')});
  await pick(580);assert.equal(await selected(),2);assert.equal(parseFloat(await page.locator('#heightValue').textContent()),height);
  const idle=await page.locator('#sunOverlay').evaluate(el=>new Promise(r=>{let n=0;const o=new MutationObserver(()=>n++);o.observe(el,{subtree:true,attributes:true,childList:true});setTimeout(()=>{o.disconnect();r(n);},400);}));
  assert.equal(idle,0,'Finished animation must stop updating');
  await page.locator('#angle').fill('60');await settle();
  await pick(643);await pick(670);await settle();
  assert.ok(await page.locator('#lunarCloseup').isVisible(),'Small triangle should enlarge even before measurement');
  assert.equal(await page.locator('#lengthValue').textContent(),'—');
  await measureManually();await settle();
  assert.ok(await page.locator('#lunarCloseup').isVisible(),'Short boundary pair must retain close-up behavior');
  for(const axis of ['horizontal','vertical'])assert.equal(await page.locator(`#closeupOverlay [data-measure-axis=${axis}]`).getAttribute('stroke-dashoffset'),'0');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-step-measure-short.png')});
  await page.locator('#angle').fill('35');await settle();
  // Cancel an active animation; delayed callbacks must not restore old results.
  await page.locator('#clear').click();await pick(675);await pick(472);await page.locator('#measure').click();await waitPhase('horizontal');
  await page.locator('#angle').fill('45');await settle();
  await page.waitForTimeout(2200);assert.equal(await phase(),'idle');assert.equal(await selected(),0);assert.equal(await page.locator('#heightValue').textContent(),'—');
  await page.locator('#angle').fill('35');await settle();
  await pick(675);await pick(472);await measureManually();
  assert.equal(parseFloat(await page.locator('#heightValue').textContent()),height,'Reverse order has same result');
  await page.locator('#intensity').fill('0');await settle();
  const topBox=await page.locator('#top').boundingBox(),clip={x:topBox.x+200,y:250,width:180,height:120};
  const dark=await page.screenshot({clip});await page.locator('#intensity').fill('200');await settle();
  assert.ok(!dark.equals(await page.screenshot({clip})));assert.equal(parseFloat(await page.locator('#heightValue').textContent()),height);
  await page.locator('#intensity').fill('100');await page.locator('#clear').click();
  // Reduced motion completes the same ordered calculation without prolonged motion.
  await page.emulateMedia({reducedMotion:'reduce'});await pick(472);await pick(675);await measureManually();
  assert.equal(parseFloat(await page.locator('#heightValue').textContent()),height);
  await page.locator('#cut').fill('20');await settle();assert.equal(await selected(),0);assert.ok(await page.locator('#lunarCloseup').isHidden());
  await page.locator('#cut').fill('0');await page.setViewportSize({width:1200,height:900});await settle();
  const scaled=await page.locator('#top').boundingBox();
  for(const x of [472,675])await page.mouse.click(scaled.x+x/800*scaled.width,scaled.y+scaled.height/2);
  await measureManually();assert.equal(await selected(),2);
  const stage=await page.locator('main').boundingBox();assert.ok(Math.abs(stage.height-675)<1&&Math.abs(stage.y-112.5)<1);
  assert.deepEqual(errors,[]);console.log('Boundary-only selection, sequential animation, cancellation, reverse order, reduced motion, intensity, idle and scaled input passed.',{points,length,height});
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
