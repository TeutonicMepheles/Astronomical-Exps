const {chromium}=require('../../../node_modules/playwright');
const assert=require('node:assert/strict'),path=require('node:path'),os=require('node:os');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch();
 try{
  const page=await browser.newPage({viewport:{width:1600,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'..','index.html')).href);
  await page.waitForSelector('#confirmLight');
  assert(await page.locator('#lengthResult').isHidden(),'Hide shadow length before measurement');
  assert(await page.locator('#heightResult').isHidden(),'Hide height before calculation');
  assert(await page.locator('#formula').isHidden());
  const settle=()=>page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  const count=()=>page.locator('[data-point]').count();
  const phase=p=>page.waitForFunction(v=>document.querySelector('.view.side').dataset.measurePhase===v,p);
  const confirm=async()=>{await page.locator('#start').click();await settle();};
  const choose=async side=>{
    await page.locator(`[data-rim-candidate][data-side=${side}]`).first().click();await settle();
    assert.equal(await count(),2,'One A click creates both endpoints');
    const points=await page.locator('[data-point]').evaluateAll(es=>es.map(e=>({x:+e.dataset.modelX,y:+e.dataset.modelY,z:+e.dataset.modelZ})));
    assert(points[0].x>points[1].x,'A stays on the right of its own down-sun B, including the left rim');
    assert.equal(points[0].z,points[1].z);
    assert.equal(points[0].x<0,side==='left');
    const length=parseFloat(await page.locator('#lengthValue').textContent());
    assert(Math.abs(length-(points[0].x-points[1].x))<.011);
    const angle=+await page.locator('#angle').inputValue();
    assert(Math.abs(points[0].y-points[1].y-length*Math.tan(angle*Math.PI/180))<.02);
    assert.equal(await page.locator('[data-top-readout=length]').count(),1);
    assert.equal(await page.locator('#heightValue').textContent(),'—');
    assert(await page.locator('#lengthResult').isVisible());
    assert(await page.locator('#heightResult').isHidden(),'Selecting another peak hides the old height result');
    assert(await page.locator('#formula').isHidden());
    const legs=await page.evaluate(()=>{
      const root=document.getElementById('sunOverlay'),dots=[...root.querySelectorAll(':scope > circle')].map(e=>({x:+e.getAttribute('cx'),y:+e.getAttribute('cy')}));
      const leg=axis=>{const p=root.querySelector(`[data-measure-axis=${axis}]`),a=p.getPointAtLength(0),b=p.getPointAtLength(p.getTotalLength());return {start:{x:a.x,y:a.y},end:{x:b.x,y:b.y},visible:p.style.visibility}};
      return {a:dots[0],b:dots[1],baseline:leg('baseline'),vertical:leg('vertical')};
    });
    const near=(a,b)=>assert(Math.abs(a-b)<.01);
    near(legs.baseline.start.x,legs.b.x);near(legs.baseline.start.y,legs.b.y);
    near(legs.baseline.end.x,legs.a.x);near(legs.baseline.end.y,legs.b.y);
    near(legs.vertical.start.x,legs.a.x);near(legs.vertical.start.y,legs.b.y);
    near(legs.vertical.end.x,legs.a.x);near(legs.vertical.end.y,legs.a.y);
    assert.equal(legs.baseline.visible,'hidden','No horizontal leg before the angle demonstration');
    assert.equal(legs.vertical.visible,'hidden');

    assert.equal(await page.locator('#top').getAttribute('data-measure-zoom'),'0.66');
    assert(Number(await page.locator('#section').getAttribute('data-measure-zoom'))>1);
    for(const el of await page.locator('[data-measure-axis=horizontal]').all())assert.equal(await el.getAttribute('stroke-dashoffset'),'0');
    return length;
  };
  assert.equal(await page.locator('#intensity,#cut,#measure').count(),0,'No light-strength, free section or manual shadow-length control');
  assert.equal(await page.locator('#angle').getAttribute('min'),'35');
  assert.equal(await page.locator('#angle').getAttribute('max'),'70');
  await page.locator('#angle').focus();await page.keyboard.press('Home');await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#angle').inputValue(),'35');
  await page.keyboard.press('End');await page.keyboard.press('ArrowRight');assert.equal(await page.locator('#angle').inputValue(),'70');
  await page.locator('#angle').fill('35');await page.locator('#confirmLight').click();await settle();
  assert.equal(await page.locator('[data-rim-candidate]').count(),0,'Confirm outline before selecting');
  await page.locator('#top').click({position:{x:400,y:450}});assert.equal(await count(),0);
  await page.locator('[data-rim-handle]').first().focus();await page.keyboard.press('ArrowRight');await settle();
  assert.equal(await page.locator('#rimRadius').inputValue(),'111');
  await page.locator('#rimRadius').fill('70');await confirm();
  assert.equal(await page.locator('[data-rim-candidate]').count(),0,'Bad outline offers no interior points');
  assert.match(await page.locator('#pickInstruction').textContent(),/没有明显投影/);
  await page.locator('#rimRadius').fill('110');await settle();assert(await page.locator('#start').isVisible());
  await confirm();
  assert(await page.locator('#lengthResult').isHidden(),'Confirming the rim does not reveal results');
  assert(await page.locator('#heightResult').isHidden());
  assert((await page.locator('[data-rim-candidate][data-side=left]').count())>0);
  assert((await page.locator('[data-rim-candidate][data-side=right]').count())>0);
  await page.locator('#top').click({position:{x:400,y:450}});assert.equal(await count(),0,'Only candidate controls can select A');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-rim-candidates.png')});
  const right=await choose('right');
  const before=await page.locator('#lengthValue').textContent();
  await page.locator('#section').click({position:{x:300,y:600}});assert.equal(await page.locator('#lengthValue').textContent(),before);
  await page.evaluate(()=>{
    window.angleFrames=[];window.angleObserver=new MutationObserver(()=>{
      const baseline=document.querySelector('#sunOverlay [data-measure-axis=baseline]'),arc=document.querySelector('#sunOverlay [data-angle-arc]');
      if(baseline&&arc)window.angleFrames.push([+baseline.getAttribute('stroke-dashoffset'),+arc.getAttribute('stroke-dashoffset')]);
    });window.angleObserver.observe(document.getElementById('sunOverlay'),{subtree:true,attributes:true,childList:true});
  });
  await page.locator('#height').click();await phase('angle-done');await settle();
  assert(await page.locator('[data-solar-angle]').count());
  assert(await page.evaluate(()=>{window.angleObserver.disconnect();return window.angleFrames.some(([b,a])=>b>0&&b<1&&a===1)&&window.angleFrames.some(([b,a])=>b===0&&a>0&&a<1)}),'Lower baseline draws before the angle arc');
  assert.equal(await page.locator('#sunOverlay [data-measure-axis=vertical]').getAttribute('stroke-dashoffset'),'1','Height cannot draw before angle step completes');
  assert.equal(await page.locator('#heightValue').textContent(),'—');
  assert(+await page.locator('#sunOverlay [data-angle-label] text').getAttribute('font-size')>=22);
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-rim-angle-below.png')});
  await page.evaluate(()=>{
    window.ink=[];window.inkObserver=new MutationObserver(()=>{const p=document.querySelector('#sunOverlay [data-measure-axis=vertical]');if(p)window.ink.push(+p.getAttribute('stroke-dashoffset'));});
    window.inkObserver.observe(document.querySelector('#sunOverlay'),{subtree:true,attributes:true});
  });
  await page.locator('#height').click();await phase('done');await settle();
  assert(await page.locator('#heightResult').isVisible());
  assert(await page.locator('#formula').isVisible());
  assert(Math.abs(parseFloat(await page.locator('#heightValue').textContent())-right*Math.tan(35*Math.PI/180))<.02);
  assert(await page.evaluate(()=>{window.inkObserver.disconnect();return window.ink.some(n=>n>0&&n<1)}),'Height animation retains intermediate frames');
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-rim-right-measured.png')});
  const left=await choose('left');assert(left>=8&&left<right);
  await page.screenshot({path:path.join(os.tmpdir(),'lunar-rim-left-shadow.png')});
  // Cancel height animation via lighting change; no delayed old result may reappear.
  await page.locator('#height').click();await settle();await page.locator('#height').click();
  await page.locator('#resetLight').click();await page.locator('#angle').fill('70');await page.locator('#confirmLight').click();await confirm();await settle();await page.waitForTimeout(1100);
  assert.equal(await count(),0);assert.equal(await page.locator('#lengthValue').textContent(),'—');assert.equal(await page.locator('#heightValue').textContent(),'—');
  for(const id of ['lengthResult','heightResult','formula'])assert(await page.locator('#'+id).isHidden(),'Lighting changes hide stale results');
  assert.equal(await page.locator('[data-rim-candidate]').count(),0);assert.match(await page.locator('#status').textContent(),/没有明显投影/);
  await page.locator('#resetLight').click();await page.locator('#angle').fill('35');
  await page.locator('#confirmLight').click();await confirm();await settle();
  assert((await page.locator('[data-rim-candidate][data-side=left]').count())>0);await choose('left');
  await page.emulateMedia({reducedMotion:'reduce'});await page.locator('#height').click();await settle();await page.locator('#height').click();await phase('done');
  const idle=await page.locator('#lunarBoundaryPicker').evaluate(el=>new Promise(resolve=>{let n=0;const o=new MutationObserver(()=>n++);o.observe(el,{subtree:true,attributes:true,childList:true});setTimeout(()=>{o.disconnect();resolve(n)},400)}));
  assert.equal(idle,0,'No ongoing circle/candidate updates when idle');
  await page.locator('#clear').click();await settle();assert.equal(await count(),0);assert.equal(await page.locator('[data-rim-candidate]').count(),0);assert(await page.locator('#start').isVisible());
  for(const id of ['lengthResult','heightResult','formula'])assert(await page.locator('#'+id).isHidden(),'Reframing hides all results');
  await page.setViewportSize({width:1200,height:900});await settle();
  const handle=await page.locator('[data-rim-handle]').first().boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();
  await page.mouse.move(handle.x+handle.width/2+20,handle.y+handle.height/2,{steps:4});await page.mouse.up();await settle();
  assert(+await page.locator('#rimRadius').inputValue()>110,'Drag handle works after letterboxing');
  await page.locator('#rimRadius').fill('110');await confirm();await choose('right');
  const stage=await page.locator('main').boundingBox();assert(Math.abs(stage.height-675)<1&&Math.abs(stage.y-112.5)<1);
  assert.deepEqual(errors,[]);
  console.log('PASS adjustable outline, bilateral candidate-only A, automatic B/length, height animation, invalidation, no-shadow recovery, reduced motion, idle and scaled touch geometry.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
