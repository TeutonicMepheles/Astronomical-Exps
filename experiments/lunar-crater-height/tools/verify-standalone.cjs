const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
(async()=>{
 const root=path.resolve(__dirname,'..');
 const file=fs.readdirSync(root,{recursive:true}).find(x=>x.endsWith('crater-lab-standalone.html'));
 const browser=await chromium.launch();
 try{
  const page=await browser.newPage({viewport:{width:1600,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root,file)).href);
  await page.waitForFunction(()=>window.craterDebug&&craterDebug.stats().builds>0);
  const state=()=>page.evaluate(()=>craterDebug.experiment());
  const run=async()=>{
   const builds=await page.evaluate(()=>craterDebug.stats().builds);
   await page.locator('#runExperiment').click();
   await page.waitForFunction(()=>craterDebug.impact().phase==='falling');
   assert.equal((await state()).impacted,false,'Crater remains hidden during the fall');
   assert.ok(await page.evaluate(()=>craterDebug.meteor.visible&&craterDebug.meteor.geometry.attributes.color.count>100),'Textured 3D meteor is visible');
   await page.waitForFunction(()=>craterDebug.impact().phase==='dust');
   assert.equal((await state()).impacted,false,'Crater remains hidden in the dust cloud');
   await page.waitForFunction(()=>craterDebug.impact().generated);
   assert.equal(await page.evaluate(()=>craterDebug.impact().coverage),1,'Terrain changes only under opaque dust');
   await page.waitForFunction(()=>craterDebug.experiment().impacted&&craterDebug.impact().phase==='idle',undefined,{timeout:15000});
   await page.waitForFunction(n=>craterDebug.stats().builds>n,builds);
  };
  assert.equal((await state()).impacted,false);
  const earthMaterial=await page.evaluate(()=>({map:craterDebug.material.map.uuid,pixel:(()=>{const c=craterDebug.material.map.image.getContext('2d');return Array.from(c.getImageData(500,500,1,1).data).slice(0,3)})()}));
  assert.ok(earthMaterial.pixel[0]>earthMaterial.pixel[1]&&earthMaterial.pixel[1]>earthMaterial.pixel[2],'Earth uses brown soil');
  assert.equal(await page.locator('#stage').evaluate(el=>Math.round(el.getBoundingClientRect().width)),1184);
  const insetBox=await page.locator('#topInset').boundingBox(),mainBox=await page.locator('#stage').boundingBox();
  assert.ok(insetBox.width>=360&&insetBox.x>=mainBox.x&&insetBox.x+insetBox.width<=mainBox.x+mainBox.width,'Larger inset stays inside the main scene');
  assert.ok(await page.locator('#panel').evaluate(el=>el.scrollHeight<=el.clientHeight),'Teaching controls fit without scrolling');
  assert.equal(await page.locator('#sceneChoices button:disabled').count(),0);
  assert.equal(await page.locator('#studyFactors button').count(),3);
  await page.screenshot({path:path.join(require('node:os').tmpdir(),'lab-before-impact.png')});
  const cameraBefore=await page.evaluate(()=>craterDebug.camera.position.toArray());
  await run();
  assert.equal((await state()).records,1);assert.equal((await state()).impacted,true);
  assert.deepEqual(await page.evaluate(()=>craterDebug.camera.position.toArray()),cameraBefore,'Impact stays in the current view');
  assert.equal(await page.locator('#sectionShortcut,#sectionView,#section3d,#cut').count(),0,'Section view controls are removed');
  assert.equal(await page.evaluate(()=>craterDebug.impact().visible),false,'Impact effects stop after the crater appears');
  await page.locator('#sizeChoices button').nth(2).click();
  assert.equal((await state()).impacted,false);assert.equal((await state()).params.sizeD,300);
  await run();assert.equal((await state()).records,2);
  await page.locator('#nextExperiment').click();assert.equal((await state()).params.sizeD,50);
  assert.equal((await state()).studyVar,'speed');
  await page.locator('#sceneChoices button').nth(1).click();assert.equal((await state()).params.scene,'moon');
  assert.notEqual(await page.evaluate(()=>craterDebug.material.map.uuid),earthMaterial.map,'Moon keeps its separate texture');
  await run();
  await page.screenshot({path:path.join(require('node:os').tmpdir(),'lab-after-impact.png')});
  await run();assert.equal((await state()).records,4);
  await page.locator('#previousRecords').click();assert.equal(await page.locator('#recordRows tr').count(),3);
  await page.locator('#advancedTab').click();
  assert.ok(await page.locator('#panel').evaluate(el=>el.scrollHeight<=el.clientHeight),'Advanced controls fit without scrolling');
  await page.locator('#teachingTab').click();await page.locator('#baselineReset').click();
  assert.equal((await state()).impacted,false);assert.equal((await state()).records,4);
  await page.locator('#clearRecords').click();assert.equal((await state()).records,0);
  await run();assert.equal((await state()).records,1,'Completed impact records the result');
  await page.locator('#baselineReset').click();
  assert.equal((await state()).records,1,'Reset preserves recorded results');
  assert.equal((await state()).impacted,false);
  await page.locator('[data-factor=angle]').click();
  await page.locator('#angleChoices button').nth(2).click();assert.equal((await state()).params.angleDeg,30);
  await page.setViewportSize({width:1200,height:900});
  await page.waitForFunction(()=>document.getElementById('labShell').getBoundingClientRect().width===1200);
  const stage=await page.locator('#labShell').boundingBox();assert.equal(stage.width,1200);assert.equal(stage.height,675);
  assert.deepEqual(errors,[]);
  console.log('Initial surface, variable locks, meteor fall, dust reveal, records, environment and reset passed.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
