"""Extract the supplied GLB's upper surface; no third-party Python dependencies."""
from pathlib import Path
from array import array
import base64
import hashlib
import json
import math
import statistics
import struct

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '陨石坑参考/陨石坑形状修正/moon-terraprinter.com.glb'
raw = SOURCE.read_bytes()
json_length = struct.unpack_from('<I', raw, 12)[0]
gltf = json.loads(raw[20:20 + json_length])
accessor = gltf['accessors'][0]
buffer_view = gltf['bufferViews'][accessor['bufferView']]
offset = 28 + json_length + buffer_view.get('byteOffset', 0) + accessor.get('byteOffset', 0)
vertices = array('f')
vertices.frombytes(raw[offset:offset + accessor['count'] * 12])
SEGMENTS = 400
N = SEGMENTS + 1
SCALE = 1.6  # Uniform XYZ conversion: source diameter 200 -> existing world width 320.
heights = [float('-inf')] * (N * N)
surface_triangles = 0
for i in range(0, len(vertices), 9):
    ax, ay, az, bx, by, bz, cx, cy, cz = vertices[i:i + 9]
    area = (bx-ax)*(cy-ay)-(by-ay)*(cx-ax)
    if area <= 1e-9:  # Exclude the printing bottom and vertical perimeter walls.
        continue
    surface_triangles += 1
    x0 = max(0, math.ceil((min(ax,bx,cx)+100)*2))
    x1 = min(SEGMENTS, math.floor((max(ax,bx,cx)+100)*2))
    z0 = max(0, math.ceil((100-max(ay,by,cy))*2))
    z1 = min(SEGMENTS, math.floor((100-min(ay,by,cy))*2))
    for iz in range(z0,z1+1):
        y = 100-iz/2
        for ix in range(x0,x1+1):
            x = ix/2-100
            u = ((x-ax)*(cy-ay)-(y-ay)*(cx-ax))/area
            v = ((bx-ax)*(y-ay)-(by-ay)*(x-ax))/area
            if u >= -1e-6 and v >= -1e-6 and u+v <= 1+1e-6:
                index = iz*N+ix
                heights[index] = max(heights[index], az+u*(bz-az)+v*(cz-az))

valid = [math.isfinite(h) for h in heights]
assert sum(valid) > N*N*.7, 'Incomplete upper surface'
perimeter = [h for i,h in enumerate(heights) if valid[i] and
             90 < math.hypot(i%N/2-100,100-i//N/2) < 95]
datum = statistics.median(perimeter)
# A radial continuation fills the surrounding viewport only. The validity mask prevents
# the extrapolated apron from being selected as measured source terrain.
for iz in range(N):
    for ix in range(N):
        index = iz*N+ix
        if valid[index]:
            continue
        dx,dz = ix-SEGMENTS/2,iz-SEGMENTS/2
        radius = math.hypot(dx,dz)
        for r in range(min(SEGMENTS//2,math.floor(radius)),0,-1):
            j = round(SEGMENTS/2+dz*r/radius)*N+round(SEGMENTS/2+dx*r/radius)
            if valid[j]:
                heights[index] = heights[j]
                break
        assert math.isfinite(heights[index])

values = array('f', ((h-datum)*SCALE for h in heights))
metadata = dict(source=SOURCE.relative_to(ROOT).as_posix(), sha256=hashlib.sha256(raw).hexdigest(),
                sourceTriangles=accessor['count']//3, surfaceTriangles=surface_triangles,
                segments=SEGMENTS, size=320, uniformScale=SCALE, sourceDatum=datum,
                sourceExtras=gltf['nodes'][0].get('extras',{}))
encoded = base64.b64encode(values.tobytes()).decode('ascii')
mask = base64.b64encode(bytes(valid)).decode('ascii')
output = '// Generated by tools/generate-reference-terrain.py; preserve source credits below.\n'
output += 'window.LunarReferenceTerrainData = '+json.dumps(dict(metadata=metadata,heights=encoded,mask=mask),ensure_ascii=False,separators=(',',':'))+';\n'
target = ROOT / 'assets/reference-terrain.js'
target.write_text(output,encoding='utf-8')
print(json.dumps(dict(metadata=metadata, validSamples=sum(valid),heightRange=[min(values),max(values)],bytes=target.stat().st_size),ensure_ascii=False))
