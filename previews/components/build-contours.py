"""Build outline geometry only; source artwork remains unchanged.
Run manually after changing mirror assets. OpenCV is a development dependency.
"""
from pathlib import Path
import json
import cv2
import numpy as np
root = Path(__file__).resolve().parent
result = {}
for name in ('plane', 'convex', 'concave'):
    raw = np.fromfile(root.parent / 'assets' / 'mirrors' / f'{name}-v2.png', dtype=np.uint8)
    image = cv2.imdecode(raw, cv2.IMREAD_UNCHANGED)
    alpha = cv2.GaussianBlur(image[:, :, 3], (5, 5), 1)
    contours, _ = cv2.findContours((alpha >= 51).astype(np.uint8) * 255, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    # These three mirror silhouettes are convex. The hull bridges translucent
    # bevel notches; this asset-specific assumption does not enter the component.
    hull = cv2.convexHull(max(contours, key=cv2.contourArea))
    points = cv2.approxPolyDP(hull, 1.5, True)[:, 0, :].astype(float)
    start = (points[-1] + points[0]) / 2
    commands = [f'M{start[0]:.1f},{start[1]:.1f}']
    for i, p in enumerate(points):
        end = (p + points[(i + 1) % len(points)]) / 2
        commands.append(f'Q{p[0]:.1f},{p[1]:.1f} {end[0]:.1f},{end[1]:.1f}')
    commands.append('Z')
    result[name] = {'viewBox': f'0 0 {image.shape[1]} {image.shape[0]}', 'path': ' '.join(commands)}
(root / 'mirror-contours.js').write_text('// Generated by build-contours.py; no runtime image processing.\nwindow.PreviewMirrorContours = ' + json.dumps(result, indent=2) + ';\n', encoding='utf-8')
print('Generated three smooth external contours.')
