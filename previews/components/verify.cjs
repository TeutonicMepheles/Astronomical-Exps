const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400) errors.push(r.url());});
  await page.goto((process.env.BASE_URL || 'http://127.0.0.1:8793') + '/previews/components/legacy-overview.html');
  await page.locator('#plane img').evaluate(img=>img.decode());
  await page.locator('.hand-choice img').evaluateAll(images=>Promise.all(images.map(image=>image.decode())));
  assert.equal(await page.evaluate(()=>typeof window.Newton),'undefined');
  assert.equal(await page.locator('.hand-choice').count(),10);
  assert.equal(await page.locator('.hand-choice img').count(),10);
  for(const id of await page.locator('.hand-choice').evaluateAll(els=>els.map(el=>el.dataset.icon))){
    await page.locator(`.hand-choice[data-icon="${id}"]`).click();
    assert.equal(await page.locator('.exp-gesture').getAttribute('data-icon'),id);
    assert.equal(await page.locator('.hand-choice[aria-pressed=true]').count(),1);
  }
  await page.locator('.hand-choice[data-icon=cream]').click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  assert.equal(await page.locator('.exp-drag-trail').count(),1);
  assert.equal(await page.locator('.exp-drag-trail').evaluate(e=>getComputedStyle(e).pointerEvents),'none');
  assert.equal(await page.locator('.trail-base').evaluate(e=>getComputedStyle(e).strokeDasharray),'none');
  assert.equal(await page.locator('.target-ring').evaluate(e=>getComputedStyle(e).borderTopStyle),'solid');
  await page.locator('.exp-hand-image').evaluate(image=>image.decode());
  assert.equal(await page.locator('feMorphology').count(),0);
  // Freeze the animation at its midpoint for a repeatable visual inspection.
  await page.evaluate(()=>document.getAnimations().forEach(a=>{a.pause();a.currentTime=1800;}));
  await page.screenshot({path:'artifacts/interaction-preview-drag.png',fullPage:false});
  await page.evaluate(()=>document.getAnimations().forEach(a=>a.play()));
  await page.locator('#gesture-toggle').uncheck({force:true});
  assert.equal(await page.locator('.exp-drag-trail').count(),0);
  await page.locator('#gesture-toggle').check({force:true});
  await page.locator('#plane').click();
  assert.equal(await page.locator('.exp-bubble').innerText(),'平面镜');
  assert.equal(await page.locator('.exp-bubble').evaluate(e=>getComputedStyle(e).pointerEvents),'none');
  await page.locator('#bubble-toggle').uncheck({force:true});
  assert.equal(await page.locator('.exp-bubble').count(),0);
  await page.locator('#outline-toggle').uncheck({force:true});
  assert.equal(await page.locator('.exp-affordance').count(),0);
  await page.locator('#outline-toggle').check({force:true});
  await page.locator('#bubble-toggle').check({force:true});
  await page.locator('[data-mode=drag]').click();
  assert.equal(await page.locator('.exp-gesture').getAttribute('data-mode'),'drag');
  const a=await page.locator('#concave').boundingBox(), b=await page.locator('#drop-zone').boundingBox();
  await page.mouse.move(a.x+a.width/2,a.y+a.height/2); await page.mouse.down();
  await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:16}); await page.mouse.up();
  assert.match(await page.locator('#feedback').innerText(),/放好了/);
  await page.locator('#reset').click();
  await page.locator('#concave').focus(); await page.keyboard.press('Enter');
  await page.locator('#drop-zone').focus(); await page.keyboard.press('Enter');
  assert.match(await page.locator('#feedback').innerText(),/放好了/);
  await page.locator('#reset').click(); await page.locator('[data-mode=tap]').click();
  await page.locator('#plane').hover(); await page.waitForTimeout(400);
  await page.screenshot({path:'artifacts/interaction-preview-desktop.png',fullPage:true});
  await page.locator('#hand-gallery').screenshot({path:'artifacts/generated-hand-choices.png'});
  await page.keyboard.press('Escape'); assert.equal(await page.locator('.exp-bubble').count(),0);
  await page.emulateMedia({reducedMotion:'reduce'}); await page.locator('#reset').click();
  assert.equal(await page.locator('.exp-gesture').evaluate(e=>getComputedStyle(e).animationName),'none');
  await page.setViewportSize({width:390,height:844}); await page.locator('#convex').click();
  const bubble=await page.locator('.exp-bubble').boundingBox(); assert(bubble.x>=0 && bubble.x+bubble.width<=390);
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'artifacts/interaction-preview-mobile.png',fullPage:true});
  // Destroy removes only owned description IDs and overlay nodes.
  await page.evaluate(()=>{
    const target=document.getElementById('plane');target.setAttribute('aria-describedby','existing-description');
    const bubble=new ExperimentHints.NameBubble();bubble.show({target,text:'<literal>'});bubble.destroy();
    if(target.getAttribute('aria-describedby')!=='existing-description')throw Error('description overwritten');
    const hint=new ExperimentHints.AffordanceHint(target.querySelector('img'),{contour:PreviewMirrorContours.plane});
    hint.setEnabled(true);const owned=hint.layer;hint.destroy();
    if(owned.isConnected)throw Error('outline layer leaked');
  });
  await page.goto(pathToFileURL(path.resolve(__dirname,'legacy-overview.html')).href);
  await page.locator('#plane').click(); assert.equal(await page.locator('.exp-bubble').innerText(),'平面镜');
  const touch = await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
  await touch.goto((process.env.BASE_URL || 'http://127.0.0.1:8793') + '/previews/components/legacy-overview.html');
  const cdp = await touch.context().newCDPSession(touch);
  const start=await touch.locator('#concave').boundingBox(), end=await touch.locator('#drop-zone').boundingBox();
  const x=start.x+start.width/2,y=start.y+start.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  for(let i=1;i<=12;i++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+(end.x+end.width/2-x)*i/12,y:y+(end.y+end.height/2-y)*i/12}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.match(await touch.locator('#feedback').innerText(),/放好了/);
  await touch.close();
  assert.deepEqual(errors,[]);
  await browser.close(); console.log('PASS: mouse and touch drag, keyboard placement, independent toggles, overlay click-through, Escape, reduced motion, mobile bounds, cleanup, file://, no runtime/resource errors');
})().catch(e=>{console.error(e);process.exit(1);});
